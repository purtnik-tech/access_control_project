"""
Конфигурация приложения access_control для Django.
Определяет основные настройки и поведение приложения при запуске.
"""

from django.apps import AppConfig
from typing import NoReturn


class AccessControlConfig(AppConfig):
    """
    Класс конфигурации для приложения access_control.
    Наследуется от базового класса AppConfig Django.
    """

    # Тип автоматического поля по умолчанию для моделей
    # BigAutoField - 64-битное целое, поддерживает до 9.2 квинтиллионов записей
    default_auto_field: str = 'django.db.models.BigAutoField'

    # Полное имя приложения (используется в INSTALLED_APPS и для путей импорта)
    name: str = 'access_control'

    def ready(self) -> None:
        """
        Метод, вызываемый Django при загрузке приложения.
        Выполняется один раз при старте сервера (не при каждом запросе).

        Здесь можно выполнять инициализацию, которая должна произойти
        единожды при запуске приложения.

        Примечание: Камера НЕ инициализируется здесь, чтобы избежать:
        - Долгой загрузки при старте сервера
        - Проблем с многопоточностью при автоматической перезагрузке
        - Захвата ресурсов камеры без необходимости

        Инициализация камеры происходит лениво (lazy initialization)
        в views.py при первом обращении к странице.
        """
        pass  # Инициализация отложена до первого запроса